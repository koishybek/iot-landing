export function getCollection(slug: string): Collection | undefined {
  return COLLECTIONS.find((c) => c.slug === slug);
}

export function getCollectionProducts(collection: Collection): CollectionProduct[] {
  return products.filter(collection.matches);
}

/** Адреса всех подборок — для карты сайта и пререндера. */
export function getCollectionRoutes(): string[] {
  return COLLECTIONS.map((c) => `/catalog/${c.slug}`);
}
