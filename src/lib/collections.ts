import productsData from "../data/products.json";

/**
 * Посадочные страницы каталога.
 *
 * Фильтры в каталоге живут в состоянии React, поэтому у отфильтрованной выборки
 * нет собственного адреса — и ранжировать по запросу «счётчики воды LoRaWAN»
 * поисковику нечего. Каждая подборка отсюда получает постоянный адрес,
 * заголовок и вступительный текст, то есть становится полноценной страницей.
 *
 * Модуль читают браузер и сборка: никаких обращений к window/document.
 */

export interface CollectionProduct {
  id: string;
  name: string;
  image?: string;
  priceText?: string;
  diameter?: string;
  badge?: string;
  category?: string;
  protocols?: string[];
  tags?: string[];
  description?: string;
}

const products = productsData as CollectionProduct[];

export interface Collection {
  slug: string;
  /** Заголовок H1 на самой странице. */
  h1: string;
  /** Тег <title>. */
  title: string;
  /** Мета-описание. */
  description: string;
  /** Вступительный абзац: у каждой подборки свой, иначе страницы дублируют друг друга. */
  intro: string;
  /** Короткая подпись для перелинковки из каталога. */
  teaser: string;
  matches: (product: CollectionProduct) => boolean;
}

const hasProtocol = (p: CollectionProduct, prefix: string) =>
  (p.protocols || []).some((x) => x.startsWith(prefix));

